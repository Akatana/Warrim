"""Makes `content/classic_start.ron`: what the original game (1.12.1) dresses a new character in, by race and sex, from the client's CharStartOutfit.dbc.

Where the data comes from (kept in tools/data, which is not shipped):
  wowtool extract DBFilesClient\CharStartOutfit.dbc tools/data/CharStartOutfit.dbc

The game has no classes but the paladin's tables, so a race gets the paladin's outfit, and one that cannot be a paladin the warrior's.
The hearthstone is left out (a new character does not start with one).

Usage: py -3 tools/import_start.py [folder with CharStartOutfit.dbc (default: tools/data)] [content folder]
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dbc import Dbc
from import_items import ALIASES

PALADIN, WARRIOR, HEARTHSTONE = 2, 1, 6948
ROW_FIELDS, ITEMS = 38, 12  # id, race/class/sex/outfit bytes, 12 item entries, 12 display ids, 12 inventory types


def main(data, content):
    t = Dbc(os.path.join(data, "CharStartOutfit.dbc"))
    t.fields = ROW_FIELDS  # the header of this table says 41; the rows are 152 bytes
    ours = set(re.findall(r'\(id: "([^"]+)"', open(os.path.join(content, "classic_items.ron"), encoding="utf8").read()))
    outfits = {}
    for r in range(t.count):
        packed = t.u32(r, 1)
        race, cls, sex = packed & 255, packed >> 8 & 255, packed >> 16 & 255
        if cls in (PALADIN, WARRIOR):
            outfits[(race, sex, cls)] = [t.i32(r, 2 + i) for i in range(ITEMS)]
    out = ["// Generated by tools/import_start.py from CharStartOutfit.dbc: what a new character of a race and sex puts on (race = row of ChrRaces.dbc, sex 0 male, 1 female).", "["]
    for race, sex in sorted({(r, s) for r, s, _ in outfits}):
        entries = outfits.get((race, sex, PALADIN)) or outfits[(race, sex, WARRIOR)]
        ids = []
        for e in entries:
            if e > 0 and e != HEARTHSTONE:
                ids.append(ALIASES.get(e, "i%d" % e))
        assert all(i in ours or i in ALIASES.values() for i in ids), (race, sex, ids)
        out.append("    (race: %d, sex: %d, items: [%s])," % (race, sex, ", ".join('"%s"' % i for i in ids)))
    out.append("]")
    open(os.path.join(content, "classic_start.ron"), "w", encoding="utf8", newline="\n").write("\n".join(out) + "\n")
    print("%d outfits" % (len(out) - 3))


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "data"), sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "content"))
