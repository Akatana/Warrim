"""Makes `content/classic_pet_stats.ron`: what the original (CMaNGOS `pet_levelstats`) gives a pet at each level of its master, for the warlock's demons and the
other pets of the table: health, mana, intellect and spirit (its mana is the most it has, and its spirit makes it regenerate).

Usage: py -3 tools/import_pet_stats.py [db.sql (default: tools/data/db.sql)] [content folder]
"""
import os
import re
import sys


def main(db, content):
    rows = {}
    for line in open(db, encoding="utf-8", errors="replace"):
        if line.startswith("INSERT INTO `pet_levelstats` VALUES"):
            for m in re.finditer(r"\((\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+),(\d+)\)", line):
                entry, level, hp, mana, _armor, _str, _agi, _sta, inte, spi = map(int, m.groups())
                rows.setdefault(entry, {})[level] = (hp, mana, inte, spi)
            break
    out = ["// Generated by tools/import_pet_stats.py from the CMaNGOS `pet_levelstats`: by the id of the pet's creature, for the levels 1... of its master, the", "// health, mana, intellect and spirit of the pet.", "{"]
    for entry in sorted(rows):
        levels = rows[entry]
        assert sorted(levels) == list(range(1, len(levels) + 1)), entry
        out.append('    "c%d": [%s],' % (entry, ", ".join("(%d, %d, %d, %d)" % levels[l] for l in sorted(levels))))
    out.append("}")
    open(os.path.join(content, "classic_pet_stats.ron"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("%d pets" % len(rows))


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "data", "db.sql"), sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "content"))
