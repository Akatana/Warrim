"""Makes `content/classic_creature_motion.ron`: how each creature of the original moves and reaches, from the CMaNGOS database: the walk and run speed (rates of the base
2.5 and 7.0 yards a second: the template's, else its model's, else 1), the combat reach of its model (what the reach of a blow is made of), the leash (yards from
where the fight began that it may be led, 0 for the default of the world) and the pursuit (milliseconds it keeps after a player who does nothing, 0 for the default).

Usage: py -3 tools/import_creature_motion.py [db.sql (default: tools/data/db.sql)] [content folder]
"""
import os
import sys

import classicdb


def main(db, content):
    models = {r["modelid"]: r for r in classicdb.rows(db, "creature_model_info")}
    out = ["// Generated by tools/import_creature_motion.py from the CMaNGOS creature_template and creature_model_info: by the id of the creature, (walk rate, run rate,",
           "// combat reach of the model in yards, leash in yards, pursuit in milliseconds). Rates are of the base speeds 2.5 and 7.0 yards a second.", "{"]
    count = 0
    for t in classicdb.rows(db, "creature_template"):
        model = next((models[m] for m in (t["ModelId1"], t["ModelId2"], t["ModelId3"], t["ModelId4"]) if m in models), None)
        walk = t["SpeedWalk"] or (model["SpeedWalk"] if model and model["SpeedWalk"] else 1.0)
        run = t["SpeedRun"] or (model["SpeedRun"] if model and model["SpeedRun"] else 1.0)
        reach = model["combat_reach"] if model else 0.0
        out.append('    "c%d": (%g, %g, %g, %g, %d),' % (t["Entry"], walk, run, reach, t["Leash"] or 0, t["Pursuit"] or 0))
        count += 1
    out.append("}")
    open(os.path.join(content, "classic_creature_motion.ron"), "w", encoding="utf-8", newline="\n").write("\n".join(out) + "\n")
    print("%d creatures" % count)


if __name__ == "__main__":
    here = os.path.dirname(os.path.abspath(__file__))
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "data", "db.sql"), sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "..", "content"))
